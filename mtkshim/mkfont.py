#!/usr/bin/env python3
"""Generate font5x7.h for the shim's framebuffer text: printable ASCII 32..126 in the classic 5x7
cell, one byte per column, bit 0 the top row. Rendered from Pillow's built-in bitmap font so the
glyphs are built, not pasted; falls back to a block for anything the font lacks."""
import sys
try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("mkfont.py: needs Pillow (pip install pillow)")
font = ImageFont.load_default()
out = ["/* generated by mkfont.py: 5x7 glyphs for ASCII 32..126, one byte per column, bit 0 = top row */",
       "static const unsigned char font5x7[95][5] = {"]
for code in range(32, 127):
    im = Image.new("1", (8, 12), 0)
    d = ImageDraw.Draw(im)
    d.text((0, -1), chr(code), font=font, fill=1)
    # find the glyph's own box and scale it into 5x7
    px = im.load()
    xs = [x for x in range(8) for y in range(12) if px[x, y]]
    ys = [y for x in range(8) for y in range(12) if px[x, y]]
    cols = [0] * 5
    if xs:
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        w, h = x1 - x0 + 1, y1 - y0 + 1
        for cx in range(5):
            for cy in range(7):
                sx = x0 + cx * w // 5
                sy = y0 + cy * h // 7
                if px[sx, sy]:
                    cols[cx] |= 1 << cy
    out.append("\t{" + ", ".join(f"0x{c:02x}" for c in cols) + f"}}, /* '{chr(code) if code != 92 else 'backslash'}' */")
out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "font5x7.h", "w").write("\n".join(out) + "\n")
print(f"font5x7.h: {len(out) - 3} glyphs")
